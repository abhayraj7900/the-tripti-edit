create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
-- Public catalogue policies also evaluate this helper for anonymous visitors.
-- auth.uid() is null for them, so the function safely returns false.
grant execute on function public.is_admin() to anon, authenticated;

