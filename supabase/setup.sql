create or replace function public.place_order(
  p_customer_name text,
  p_phone text,
  p_address text,
  p_payment_method text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid := gen_random_uuid();
  v_order_number text := 'TJ-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
  v_email text;
  v_subtotal integer := 0;
  v_shipping integer := 0;
  v_free_shipping integer := 999;
  v_standard_shipping integer := 79;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_size text;
begin
  if v_user_id is null then
    raise exception 'Please sign in before placing an order.';
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your shopping bag is empty.';
  end if;

  select email into v_email from public.profiles where id = v_user_id;
  if v_email is null then
    raise exception 'Customer profile was not found.';
  end if;

  insert into public.orders (id, order_number, user_id, customer_name, email, phone, address, payment_method)
  values (v_order_id, v_order_number, v_user_id, trim(p_customer_name), v_email, trim(p_phone), trim(p_address), coalesce(nullif(trim(p_payment_method), ''), 'To be confirmed'));

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := greatest(1, least(10, coalesce((v_item ->> 'quantity')::integer, 1)));
    v_size := coalesce(v_item ->> 'size', '');

    select * into v_product
    from public.products
    where id = (v_item ->> 'id')::bigint and is_active = true
    for update;

    if not found then
      raise exception 'A product in your bag is no longer available.';
    end if;
    if v_product.stock < v_quantity then
      raise exception 'Not enough stock for %.', v_product.name;
    end if;

    v_subtotal := v_subtotal + (v_product.price * v_quantity);
    insert into public.order_items (order_id, product_id, product_name, price, quantity, size)
    values (v_order_id, v_product.id, v_product.name, v_product.price, v_quantity, v_size);
    update public.products set stock = stock - v_quantity where id = v_product.id;
  end loop;

  select free_shipping_minimum, standard_shipping
  into v_free_shipping, v_standard_shipping
  from public.site_settings where id = 1;

  v_shipping := case when v_subtotal >= coalesce(v_free_shipping, 999) then 0 else coalesce(v_standard_shipping, 79) end;
  update public.orders
  set subtotal = v_subtotal, shipping = v_shipping, total = v_subtotal + v_shipping
  where id = v_order_id;

  return jsonb_build_object(
    'id', v_order_id,
    'order_number', v_order_number,
    'subtotal', v_subtotal,
    'shipping', v_shipping,
    'total', v_subtotal + v_shipping
  );
end;
$$;

revoke all on function public.place_order(text, text, text, text, jsonb) from public;
grant execute on function public.place_order(text, text, text, text, jsonb) to authenticated;
